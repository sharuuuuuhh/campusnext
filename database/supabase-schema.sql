-- 1. USERS: Identity & Authentication
CREATE TABLE IF NOT EXISTS users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(140) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  phone_no VARCHAR(32),
  role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT', 'OWNER', 'ADMIN')),
  account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE', 'DISABLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. PG_OWNERS: Owner Profile & Verification Details
CREATE TABLE IF NOT EXISTS pg_owners (
  owner_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT UNIQUE,
  demo_key VARCHAR(100) UNIQUE,
  owner_name VARCHAR(140) NOT NULL,
  contact_no VARCHAR(32) NOT NULL,
  address TEXT NOT NULL,
  id_proof VARCHAR(180),
  proof_original_name VARCHAR(180),
  proof_media_type VARCHAR(80),
  proof_reviewed_at TIMESTAMPTZ NULL,
  owner_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (owner_status IN ('PENDING', 'APPROVED', 'REJECTED')),
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pg_owner_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE SET NULL
);

-- 3. PG_DETAILS: Accommodation Listings
CREATE TABLE IF NOT EXISTS pg_details (
  pg_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT NOT NULL,
  demo_key VARCHAR(100) UNIQUE,
  pg_name VARCHAR(100) NOT NULL,
  gender_type VARCHAR(20) NOT NULL CHECK (gender_type IN ('BOYS', 'GIRLS')),
  monthly_rent NUMERIC(10,2) NOT NULL,
  room_type VARCHAR(20) NOT NULL DEFAULT 'Shared' CHECK (room_type IN ('Shared', 'Single')),
  food_facility BOOLEAN NOT NULL DEFAULT FALSE,
  total_beds INT NOT NULL DEFAULT 1,
  vacant_beds INT NOT NULL DEFAULT 0,
  dist_from_coet NUMERIC(4,1) NOT NULL,
  pg_address VARCHAR(255) NOT NULL,
  amenities_json TEXT NOT NULL DEFAULT '[]',
  description TEXT,
  moderation_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (moderation_status IN ('PENDING', 'APPROVED', 'REJECTED')),
  is_visible BOOLEAN NOT NULL DEFAULT TRUE,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pg_details_owner FOREIGN KEY (owner_id) REFERENCES pg_owners(owner_id) ON DELETE CASCADE,
  CONSTRAINT chk_pg_vacant_beds CHECK (vacant_beds <= total_beds)
);

-- 4. INQUIRIES: Student Messages to PG Owners
CREATE TABLE IF NOT EXISTS inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pg_id BIGINT NOT NULL,
  student_user_id BIGINT NULL,
  sender_name VARCHAR(140) NOT NULL,
  sender_phone VARCHAR(32) NOT NULL,
  message VARCHAR(2000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'READ', 'CLOSED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_inquiry_pg FOREIGN KEY (pg_id) REFERENCES pg_details(pg_id) ON DELETE CASCADE,
  CONSTRAINT fk_inquiry_student FOREIGN KEY (student_user_id) REFERENCES users(user_id) ON DELETE SET NULL
);

-- 5. FEEDBACK: User Reports and Inquiries
CREATE TABLE IF NOT EXISTS feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NULL,
  name VARCHAR(140) NOT NULL,
  email VARCHAR(190),
  message VARCHAR(2000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'REVIEWED', 'CLOSED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_feedback_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE SET NULL
);

-- 6. Indexes for Performance
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_pg_details_search ON pg_details(is_visible, moderation_status, gender_type, monthly_rent, dist_from_coet);
CREATE INDEX IF NOT EXISTS idx_inquiry_pg ON inquiries(pg_id, created_at);

